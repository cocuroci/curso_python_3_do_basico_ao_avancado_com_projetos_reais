"""
Python = Linguagem de programação
Tipo de tipagem = Dinamica/Forte
str -> string -> texto
Strings são textos que estão dentro de aspas
"""

# Aspas simples
print('André')
print(1, '"André"', end='\n\n')

# Aspas duplas
print("André")
print(2, "'André'", end='\n\n')

# Escape
print("André \'Sobrenome\'")

# r
print(r"André \'Sobrenome\'")